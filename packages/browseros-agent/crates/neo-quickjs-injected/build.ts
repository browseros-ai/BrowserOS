/**
 * Bundles src/ into dist/sdk.js for neo-runtime to embed. The output is a classic script,
 * not a module: QuickJS evaluates it and takes its completion value, `{ createRun, createHooks }`
 * (the agent's realm calls `createRun`, a run's hook realm `createHooks`). Bun cannot emit that
 * shape, so this wraps Bun's ESM output in an arrow function that returns the exports, which also
 * keeps every top-level name out of the realm's globals.
 */

import { dirname, relative } from 'node:path'
import type { BunPlugin } from 'bun'

/**
 * Playwright's value serializers name globals QuickJS lacks (`URL`, `Buffer`, `atob`, `btoa`).
 * This binds them, inside those two vendored modules only, to `src/vendor-shims.ts` by
 * prepending one import while bundling: the files on disk stay byte-identical (`vendor.test.ts`)
 * and the realm gains no global.
 */
const SHIMMED =
  /\/vendor\/playwright\/(protocol\/src\/serializers|isomorphic\/utilityScriptSerializers)\.ts$/
const vendorShims: BunPlugin = {
  name: 'vendor-shims',
  setup(build) {
    build.onLoad({ filter: SHIMMED }, async (args) => {
      const shims = relative(
        dirname(args.path),
        `${import.meta.dir}/src/vendor-shims`,
      )
      const source = await Bun.file(args.path).text()
      return {
        contents: `import { URL, Buffer, atob, btoa } from '${shims}';\n${source}`,
        loader: 'ts',
      }
    })
  },
}

const result = await Bun.build({
  entrypoints: [`${import.meta.dir}/src/index.ts`],
  format: 'esm',
  target: 'browser',
  plugins: [vendorShims],
})
const [output] = result.outputs
if (!result.success || result.outputs.length !== 1 || !output) {
  throw new AggregateError(result.logs, 'neo-quickjs-injected build failed')
}

/** Neo: what the bundle's completion value holds, the only names `src/index.ts` may export. */
const EXPORTS = ['createHooks', 'createRun']

const exportStatement = /^export \{([\s\w,]*)\};\s*$/m
const esm = await output.text()
const exported = esm
  .match(exportStatement)?.[1]
  ?.split(',')
  .map((name) => name.trim())
  .filter(Boolean)
  .sort()
if (
  esm.match(/^export /gm)?.length !== 1 ||
  exported?.join() !== EXPORTS.join()
) {
  throw new Error(
    `neo-quickjs-injected build: expected exactly one \`export { ${EXPORTS.join(', ')} };\` statement`,
  )
}
const body = esm.replace(exportStatement, '').trimEnd()
await Bun.write(
  `${import.meta.dir}/dist/sdk.js`,
  `// Generated by build.ts from src/. Do not edit.\n(() => {\n'use strict';\n${body}\nreturn { createRun, createHooks };\n})();\n`,
)
