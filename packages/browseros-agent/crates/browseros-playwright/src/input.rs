//! `page.keyboard` and `page.mouse`: stateful per page as in Playwright (held modifiers and
//! keys, the pointer's position and buttons), sent as trusted CDP input on the page's root
//! session, which routes keys to the focused frame and the mouse by hit testing.
//!
//! ```text
//!  input_op (keyboard.*, mouse.*)  ─┐
//!  pointer and text actions        ─┴▶ PageInput (the tab's input lock, owned for one burst)
//!                                        └▶ InputDevices { Keyboard, Mouse }   state + port of upstream
//!                                             └▶ Vec<InputStep>               the burst, sent in order
//!  us_keyboard_layout, mac_editing_commands: upstream's tables, generated by
//!  packages/browseros-playwright-js/scripts/port-keyboard-layout.ts
//! ```

mod input_devices;
pub(crate) mod input_op;
mod keyboard;
mod mac_editing_commands;
mod mouse;
mod page_input;
mod typed;
mod us_keyboard_layout;

pub(crate) use input_devices::{InputDevices, InputStep, approach, copies, waits};
pub(crate) use input_op::{InputOp, burst_failed, hold, millis};
pub(crate) use keyboard::{Keyboard, Modifiers, Platform, UnknownKey};
pub(crate) use mouse::{ClickOptions, MouseButton, Point};
pub(crate) use page_input::{BurstFailure, PageInput, TabInput};
pub(crate) use typed::Typed;
