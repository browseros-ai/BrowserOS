/**
 * Ports Playwright's keyboard data from the vendored sources to Rust, so the crate's keyboard
 * sends what upstream sends without anyone retyping a table:
 *
 *   third_party/playwright/.../server/usKeyboardLayout.ts
 *       → crates/neo-sdk/neo-playwright/src/input/us_keyboard_layout.rs
 *   third_party/playwright/.../server/macEditingCommands.ts
 *       → crates/neo-sdk/neo-playwright/src/input/mac_editing_commands.rs
 *
 * The tables are read by importing the vendored modules, so the values are exactly what
 * upstream's own code sees; only the row comments are taken from the source text. Each Rust
 * file keeps its upstream file's Apache header. `bun scripts/port-keyboard-layout.ts` writes
 * them, and `--check` (run by the package's tests) fails when a committed copy is stale. The
 * Rust tables carry `#[rustfmt::skip]` so each keeps one line per upstream entry.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { macEditingCommands } from '../../neo-playwright/third_party/playwright/packages/playwright-core/src/server/macEditingCommands'
import {
  keypadLocation,
  USKeyboardLayout,
} from '../../neo-playwright/third_party/playwright/packages/playwright-core/src/server/usKeyboardLayout'

const agentRoot = resolve(import.meta.dir, '../../../..')
const crateRoot = resolve(agentRoot, 'crates/neo-sdk/neo-playwright')
const upstreamServer = 'packages/playwright-core/src/server'

/** One generated file, its path relative to packages/browseros-agent. */
type Output = { path: string; text: string }

function vendored(path: string): string {
  return readFileSync(
    resolve(crateRoot, 'third_party/playwright', path),
    'utf8',
  )
}

/** The upstream file's leading license comment, as Rust line comments. */
function licenseHeader(source: string): string {
  const match = /^\/\*\*\n([\s\S]*?)\n \*\//.exec(source)
  if (!match?.[1])
    throw new Error('the vendored file has no leading license comment')
  return match[1]
    .split('\n')
    .map((line) => `//${line.replace(/^ \*/, '')}`.trimEnd())
    .join('\n')
}

/** A Rust string literal with the same characters. */
function rustString(value: string): string {
  let escaped = ''
  for (const char of value) {
    const code = char.codePointAt(0) ?? 0
    if (char === '\\' || char === '"') escaped += `\\${char}`
    else if (char === '\n') escaped += '\\n'
    else if (char === '\r') escaped += '\\r'
    else if (char === '\t') escaped += '\\t'
    else if (code < 0x20 || code === 0x7f)
      escaped += `\\u{${code.toString(16)}}`
    else escaped += char
  }
  return `"${escaped}"`
}

/** The `// Functions row` style comments above entries, by the code they precede. */
function rowComments(source: string): Map<string, string> {
  const comments = new Map<string, string>()
  let pending: string | undefined
  for (const line of source.split('\n')) {
    const comment = /^\s*\/\/ (.+)$/.exec(line)
    const entry = /^\s*'([^']+)': \{/.exec(line)
    if (comment?.[1]) pending = comment[1]
    else if (entry?.[1]) {
      if (pending) comments.set(entry[1], pending)
      pending = undefined
    }
  }
  return comments
}

function header(source: string, path: string, tag: string): string {
  return `// Generated by crates/neo-sdk/neo-playwright-js/scripts/port-keyboard-layout.ts from
// Playwright ${tag}'s ${path}, vendored under
// crates/neo-sdk/neo-playwright/third_party/playwright. Do not edit: rerun the script. The
// package's tests fail while this file is stale.
//
${licenseHeader(source)}
`
}

function usKeyboardLayout(tag: string): Output {
  const path = `${upstreamServer}/usKeyboardLayout.ts`
  const source = vendored(path)
  const comments = rowComments(source)
  const rows: string[] = []
  for (const [code, definition] of Object.entries(USKeyboardLayout)) {
    const comment = comments.get(code)
    if (comment) rows.push(`    // ${comment}`)
    if (
      definition.shiftKey !== undefined &&
      [...definition.shiftKey].length !== 1
    )
      throw new Error(`${code}: upstream asserts a one-character shiftKey`)
    const fields: string[] = []
    if (definition.keyCodeWithoutLocation !== undefined)
      fields.push(
        `key_code_without_location: Some(${definition.keyCodeWithoutLocation})`,
      )
    if (definition.shiftKey !== undefined)
      fields.push(`shift_key: Some(${rustString(definition.shiftKey)})`)
    if (definition.shiftKeyCode !== undefined)
      fields.push(`shift_key_code: Some(${definition.shiftKeyCode})`)
    if (definition.text !== undefined)
      fields.push(`text: Some(${rustString(definition.text)})`)
    if (definition.location !== undefined)
      fields.push(`location: Some(${definition.location})`)
    const base = `KeyDefinition::new(${rustString(code)}, ${rustString(definition.key)}, ${definition.keyCode})`
    rows.push(
      fields.length === 0
        ? `    ${base},`
        : `    KeyDefinition { ${fields.join(', ')}, ..${base} },`,
    )
  }
  return {
    path: 'crates/neo-sdk/neo-playwright/src/input/us_keyboard_layout.rs',
    text: `${header(source, path, tag)}
//! Playwright's US keyboard layout as data: every physical key, with the codes and characters
//! it sends. The keyboard (\`keyboard.rs\`) derives the names a key can be pressed by from it,
//! as upstream's \`buildLayoutClosure\` (server/input.ts) does.

/// One physical key, as upstream's \`KeyDefinition\` declares it. An absent field keeps
/// upstream's default, which the keyboard applies: \`keyCodeWithoutLocation || keyCode\`,
/// \`text || ''\` and \`location || 0\`.
pub(crate) struct KeyDefinition {
    /// \`KeyboardEvent.code\`, such as \`KeyA\`: the name upstream's table is keyed by.
    pub(crate) code: &'static str,
    /// \`KeyboardEvent.key\` without Shift.
    pub(crate) key: &'static str,
    /// The Windows virtual key code.
    pub(crate) key_code: u32,
    /// The virtual key code without the side, for keys that have two (16 for both Shifts).
    pub(crate) key_code_without_location: Option<u32>,
    /// \`KeyboardEvent.key\` with Shift held.
    pub(crate) shift_key: Option<&'static str>,
    /// The virtual key code with Shift held, where it differs (the numpad digits).
    pub(crate) shift_key_code: Option<u32>,
    /// What a named key types: \`Enter\` types \`\\r\`.
    pub(crate) text: Option<&'static str>,
    /// \`KeyboardEvent.location\`: 1 left, 2 right, 3 numpad.
    pub(crate) location: Option<u32>,
}

impl KeyDefinition {
    /// A key with only the fields every key has.
    const fn new(code: &'static str, key: &'static str, key_code: u32) -> Self {
        Self {
            code,
            key,
            key_code,
            key_code_without_location: None,
            shift_key: None,
            shift_key_code: None,
            text: None,
            location: None,
        }
    }
}

/// The \`location\` of numpad keys; CDP's \`isKeypad\` is true for them.
pub(crate) const KEYPAD_LOCATION: u32 = ${keypadLocation};

/// Every key, in upstream's order: as in upstream's map, a later key wins a name two keys share.
#[rustfmt::skip]
pub(crate) static US_KEYBOARD_LAYOUT: &[KeyDefinition] = &[
${rows.join('\n')}
];
`,
  }
}

function macEditingCommandsTable(tag: string): Output {
  const path = `${upstreamServer}/macEditingCommands.ts`
  const source = vendored(path)
  const rows: string[] = []
  for (const [shortcut, value] of Object.entries(macEditingCommands)) {
    const commands = typeof value === 'string' ? [value] : value
    for (const command of commands)
      if (!command.endsWith(':'))
        throw new Error(`${shortcut}: ${command} lacks the trailing ':'`)
    rows.push(
      `    EditingShortcut { shortcut: ${rustString(shortcut)}, commands: &[${commands.map(rustString).join(', ')}] },`,
    )
  }
  return {
    path: 'crates/neo-sdk/neo-playwright/src/input/mac_editing_commands.rs',
    text: `${header(source, path, tag)}
//! The editing commands Playwright sends with a key down, as CDP's \`commands\`, when the
//! browser runs on macOS (server/chromium/crInput.ts), as data. On other platforms a key down
//! sends none.

/// One shortcut and the commands it runs.
pub(crate) struct EditingShortcut {
    /// Upstream's key: the held modifiers in the order Shift, Control, Alt, Meta, then the
    /// key's code, joined by \`+\` (\`Shift+Control+KeyA\`).
    pub(crate) shortcut: &'static str,
    /// Cocoa selector names with their trailing \`:\` (\`deleteBackward:\`), as upstream has them.
    pub(crate) commands: &'static [&'static str],
}

/// Every shortcut upstream lists, in its order.
#[rustfmt::skip]
pub(crate) static MAC_EDITING_COMMANDS: &[EditingShortcut] = &[
${rows.join('\n')}
];
`,
  }
}

export function portedOutputs(): Output[] {
  const [tag = ''] = vendored('VERSION').split('\n')
  return [usKeyboardLayout(tag), macEditingCommandsTable(tag)]
}

/** The outputs whose committed copy differs from a fresh port (or is missing). */
export function staleOutputs(): string[] {
  const stale: string[] = []
  for (const output of portedOutputs()) {
    let committed: string | undefined
    try {
      committed = readFileSync(resolve(agentRoot, output.path), 'utf8')
    } catch {
      committed = undefined
    }
    if (committed !== output.text) stale.push(output.path)
  }
  return stale
}

if (import.meta.main) {
  if (process.argv.includes('--check')) {
    const stale = staleOutputs()
    if (stale.length > 0) {
      console.error(
        `Stale: ${stale.join(', ')}. Run bun scripts/port-keyboard-layout.ts.`,
      )
      process.exit(1)
    }
  } else {
    for (const output of portedOutputs())
      writeFileSync(resolve(agentRoot, output.path), output.text)
  }
}
