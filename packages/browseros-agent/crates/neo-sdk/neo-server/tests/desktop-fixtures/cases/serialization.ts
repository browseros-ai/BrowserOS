import type { CaseSpec } from '../model'
import { expectedFamilyCounts, requireCondition } from './requirements'

/** Import and offline checking share the same bytes, so a second import cannot drift silently. */
export function familyModule(file: string): {
  path: string
  exportName: string
} {
  requireCondition(
    file in expectedFamilyCounts,
    `Unknown original case file ${file}`,
  )
  const family = file.slice('cases-'.length, -'.ts'.length)
  const exportName = `${family.replace(/-([a-z])/g, (_, letter: string) => letter.toUpperCase())}Cases`
  return { path: `cases/${family}.ts`, exportName }
}

export function serializeFamily(
  file: string,
  cases: readonly CaseSpec[],
): string {
  const { exportName } = familyModule(file)
  return [
    "import type { CaseSpec } from '../model'",
    '',
    '// Generated by import.ts. Original titles, intent, and ordered calls are part of the contract.',
    '// biome-ignore format: Keep deterministic import serialization independent of formatter versions.',
    `export const ${exportName} = ${JSON.stringify(cases, null, 2)} satisfies readonly CaseSpec[]`,
    '',
  ].join('\n')
}

export function serializeJson(value: unknown): string {
  return `${JSON.stringify(value, null, 2)}\n`
}

/** Committed validation is machine-independent; only an explicit import supplies host identity. */
export function requirePublicText(
  content: string,
  context: { privateRoot?: string; importingHost?: string } = {},
): void {
  requireCondition(
    !context.privateRoot || !content.includes(context.privateRoot),
    'Emitted data contains the external input root',
  )
  requireCondition(
    context.importingHost === undefined ||
      (context.importingHost.length > 0 &&
        !content.includes(context.importingHost)),
    'Emitted data contains the importing host identity',
  )
  requireCondition(
    !/(?:\/Users\/|\/home\/|results\/(?:runs|proofs)\/|-----BEGIN [A-Z ]*PRIVATE KEY-----)/.test(
      content,
    ),
    'Emitted data contains private paths or key material',
  )
  requireCondition(
    !/(?:api[_-]?key|access[_-]?token|secret[_-]?key)\s*[=:]\s*["'][^"']+["']/i.test(
      content,
    ),
    'Emitted data contains credential material',
  )
}
