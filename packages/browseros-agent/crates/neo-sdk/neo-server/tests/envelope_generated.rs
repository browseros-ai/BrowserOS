//! The run envelope's contract with the prelude: the text a run's realm receives (its init, every
//! op's reply) and the TypeScript the prelude reads it with.
//!
//! ```text
//!  runtime/bridge.rs Envelope ─┐                  ┌─▶ neo-playwright-js/src/prelude/generated/envelope.ts
//!  runtime/run_init.rs RunInit ┴─ derive(TS) ─────┤     (written here; bridge.ts and errors.ts import it)
//!     and every type they reach                   │
//!  test_support::envelope_examples ── the bytes ──┴─▶ tests/data/envelope-examples.json
//!                                                       (pinned here; the prelude's
//!                                                        tests/prelude-envelope.test.ts reads it)
//! ```
//!
//! The TypeScript is generated: a stale `envelope.ts` is rewritten and the test fails, so the
//! regenerated file is reviewed and committed like any other change. The bytes are pinned: every
//! example must equal its entry in the JSON file, and this test never rewrites that file, since a
//! byte change is a change to the contract, made by hand on both sides.
//!
//! `envelope.ts` sits in the folder neo-playwright's `tests/wire_generated.rs` writes, which
//! leaves this one file alone. It is self-contained: every type it names is declared in it.

use std::any::TypeId;
use std::collections::BTreeMap;
use std::error::Error;
use std::path::Path;
use std::{fs, io};

use neo_server::test_support::{self, EnvelopeType};

/// From this crate's manifest directory.
const PINNED: &str = "tests/data/envelope-examples.json";

/// From this crate's manifest directory.
const GENERATED: &str = "../neo-playwright-js/src/prelude/generated/envelope.ts";

const HEADER: &str = "\
// Generated by crates/neo-sdk/neo-server/tests/envelope_generated.rs from the Rust types of the
// run envelope: runtime/bridge.rs `Envelope` (each op's reply), runtime/run_init.rs `RunInit` (a
// run's init) and every type they reach. Do not edit: change the Rust type, then run
// `cargo test -p neo-server --test envelope_generated`, which rewrites this file.
";

/// The file's text, every declaration once and in name order, or why it cannot be laid out: two
/// Rust types under one TypeScript name, or a type that names a module outside the file.
fn render(types: &[EnvelopeType]) -> Result<String, Vec<String>> {
    let mut refusals = Vec::new();
    let mut by_name: BTreeMap<&str, &EnvelopeType> = BTreeMap::new();
    for named in types {
        if let Some(first) = by_name.insert(&named.name, named)
            && first.id != named.id
        {
            refusals.push(format!(
                "{} and {} both print as TypeScript `{}`; rename one with #[ts(rename)]",
                first.rust, named.rust, named.name
            ));
        }
        if named.declaration.contains("import(") {
            refusals.push(format!(
                "{} prints an import; envelope.ts declares every type it names",
                named.rust
            ));
        }
    }
    if !refusals.is_empty() {
        return Err(refusals);
    }
    // By name: ts-rs's derive gathers each type's dependencies in a hash set, so the walk's
    // order changes from one build to the next.
    let declarations: Vec<&str> = by_name
        .values()
        .map(|named| named.declaration.as_str())
        .collect();
    Ok(format!("{HEADER}\n{}\n", declarations.join("\n\n")))
}

#[test]
fn tests_that_the_generated_envelope_types_match_the_rust_types() -> Result<(), Box<dyn Error>> {
    let text = render(&test_support::envelope_types()).map_err(|refusals| refusals.join("\n"))?;
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join(GENERATED);
    let committed = match fs::read_to_string(&path) {
        Ok(committed) => Some(committed),
        Err(error) if error.kind() == io::ErrorKind::NotFound => None,
        Err(error) => return Err(error.into()),
    };
    if committed.as_deref() == Some(text.as_str()) {
        return Ok(());
    }
    fs::write(&path, &text)?;
    Err(format!(
        "{} did not match the run envelope's Rust types and has been rewritten; review and \
         commit it",
        path.display()
    )
    .into())
}

/// A type printed twice under one name would leave the second declaration out of the file.
#[test]
fn tests_that_two_rust_types_under_one_name_are_refused() {
    let declared = |rust: &'static str, id| EnvelopeType {
        name: "Fact".to_owned(),
        declaration: "export type Fact = { tab: number, };".to_owned(),
        rust,
        id,
    };
    let refused = render(&[
        declared("a::Fact", TypeId::of::<u8>()),
        declared("b::Fact", TypeId::of::<u16>()),
    ]);
    assert!(
        refused.is_err_and(|refusals| refusals.iter().any(|refusal| refusal.contains("a::Fact"))),
        "two identities under one name are refused, naming both"
    );
}

#[test]
fn tests_that_the_envelope_bytes_match_the_pinned_examples() -> Result<(), Box<dyn Error>> {
    let rendered: BTreeMap<String, String> = test_support::envelope_examples()?
        .into_iter()
        .map(|example| (example.name.to_owned(), example.text))
        .collect();
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join(PINNED);
    let pinned: BTreeMap<String, String> = match fs::read_to_string(&path) {
        Ok(text) => serde_json::from_str(&text)?,
        Err(error) => {
            return Err(format!(
                "{}: {error}; the examples render as:\n{}",
                path.display(),
                serde_json::to_string_pretty(&rendered)?
            )
            .into());
        }
    };
    let mut differences = Vec::new();
    for (name, text) in &rendered {
        match pinned.get(name) {
            Some(expected) if expected == text => {}
            Some(expected) => {
                differences.push(format!(
                    "{name}\n    pinned:   {expected}\n    rendered: {text}"
                ));
            }
            None => differences.push(format!("{name} is not pinned; it renders as {text}")),
        }
    }
    for name in pinned.keys().filter(|name| !rendered.contains_key(*name)) {
        differences.push(format!("{name} is pinned and no longer rendered"));
    }
    assert!(
        differences.is_empty(),
        "the run envelope's bytes changed ({}); a change on purpose updates that file and the \
         prelude's tests/prelude-envelope.test.ts with it:\n  {}",
        path.display(),
        differences.join("\n  ")
    );
    Ok(())
}
