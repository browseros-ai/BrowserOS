/**
 * Bundles src/ into dist/sdk.js for neo-runtime to embed. The output is a classic script,
 * not a module: QuickJS evaluates it and takes its completion value, `{ createRun }`. Bun
 * cannot emit that shape, so this wraps Bun's ESM output in an arrow function that returns
 * the exports, which also keeps every top-level name out of the realm's globals.
 */

const result = await Bun.build({
  entrypoints: [`${import.meta.dir}/src/index.ts`],
  format: 'esm',
  target: 'browser',
})
const [output] = result.outputs
if (!result.success || result.outputs.length !== 1 || !output) {
  throw new AggregateError(result.logs, 'neo-sdk build failed')
}

const exportStatement = /^export \{\s*createRun\s*\};\s*$/m
const esm = await output.text()
if (!exportStatement.test(esm) || esm.match(/^export /gm)?.length !== 1) {
  throw new Error(
    'neo-sdk build: expected exactly one `export { createRun };` statement',
  )
}
const body = esm.replace(exportStatement, '').trimEnd()
await Bun.write(
  `${import.meta.dir}/dist/sdk.js`,
  `// Generated by build.ts from src/. Do not edit.\n(() => {\n'use strict';\n${body}\nreturn { createRun };\n})();\n`,
)
